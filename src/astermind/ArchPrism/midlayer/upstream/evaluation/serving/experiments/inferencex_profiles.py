def resolve_profile(profile_id):
    """Resolve only the selected recipe's original environment-dependent settings."""
    profile = PROFILES[profile_id]
    environment = profile['workers_environment']
    if environment is None:
        return profile
    constants = dict(profile['constants'])
    raw_workers = (os.environ[environment] if environment in os.environ
                   else str(constants['MAX_WORKERS']))
    constants['MAX_WORKERS'] = int(raw_workers)
    return profile | {'constants': constants}
